/**
 * Industry radar (1_scraping) — CHOOSING THE TARGETS, made SMART.
 *
 * The problem: "which verticals to go after" decided the possible revenue, and it was picked BY HAND.
 * The radar SCORES the trades themselves (not the prospects) on 4 dimensions and outputs a RANKED list:
 *   • TICKET VALUE    what they can pay us (the `value` baseline in industries.ts)
 *   • WEB-DECISIVE    does a beautiful site change the game? (the `lever` baseline)
 *   • SELLABLE TAM    independents in French-speaking Europe × (1 − franchise density). ← the pool-builder lesson.
 *   • RECURRING       maintenance / seasonal / loyal patients → revenue that piles up.
 *
 * SINGLE SOURCE: everything comes from `industries.ts` (one trade = one entry, scrapable + scored + radar dims).
 * Zero LLM, instant, transparent. REFINES itself: reads the learned rules (`learning/`) → a trade's
 * real conversion adjusts its rank.
 *
 * Usage: npm run radar             (ranks the whole universe + writes design/industries/RADAR.md)
 *        npm run radar -- <trade>  (one trade in detail)
 */
import { writeFile, mkdir } from "node:fs/promises"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { INDUSTRIES, type Industry } from "./industries.ts"
import { loadRules } from "../../../learning/scripts/rules.ts"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..")
const MD_PATH = join(ROOT, "design", "industries", "RADAR.md") // the ranking, as readable markdown (generated)

// defaults for the radar dimensions an entry leaves out
const DEF = { tam: 3000, franchised: 15, recurring: 30, ticket: "?" }
// Weights: TICKET and WEB-DECISIVE dominate (our business = a big basket × sold on looks).
const W = { value: 0.45, web: 0.33, tam: 0.12, recurring: 0.10 } as const
const clamp = (n: number) => Math.max(0, Math.min(100, Math.round(n)))
const tamScore = (sellable: number) => clamp((Math.log10(sellable + 1) / Math.log10(20000)) * 100)

export type Scored = {
  key: string; label: string; ticket: string
  tam: number; franchised: number; recurring: number
  value: number; web: number; sellableTam: number
  score: number; tier: "prioritaire" | "ok" | "éviter"; scrapable: boolean; why: string
}

const tierOf = (s: number) => (s >= 73 ? "prioritaire" : s >= 55 ? "ok" : "éviter") as Scored["tier"]
/** The tier as shown to a reader (the stored value stays as is). */
const TIER_EN: Record<Scored["tier"], string> = { prioritaire: "priority", ok: "ok", éviter: "avoid" }

/** Scores a trade from `industries.ts`. `valueDelta` = a learned adjustment (real conversion); 0 by default. */
export function scoreIndustry(key: string, ind: Industry, valueDelta = 0): Scored {
  const value = clamp((ind.value ?? 60) + valueDelta)
  const web = clamp(ind.lever ?? 60)
  const tam = ind.tam ?? DEF.tam
  const franchised = ind.franchised ?? DEF.franchised
  const recurring = ind.recurring ?? DEF.recurring
  const ticket = ind.ticket ?? DEF.ticket
  const sellableTam = Math.round(tam * (1 - franchised / 100))
  const score = clamp(W.value * value + W.web * web + W.tam * tamScore(sellableTam) + W.recurring * recurring)
  const scrapable = (ind.osm?.length ?? 0) > 0 || (ind.naf?.length ?? 0) > 0
  const why = `ticket ${value} · web ${web} · pool ${sellableTam.toLocaleString("fr")} independents (${franchised}% franchised) · recurring ${recurring}`
  return { key, label: ind.label, ticket, tam, franchised, recurring, value, web, sellableTam, score, tier: tierOf(score), scrapable, why }
}

/** Ranks ALL of industries.ts, applying the learned adjustments (learning) if any. */
export async function rankIndustries(): Promise<Scored[]> {
  const rules = await loadRules()
  return Object.entries(INDUSTRIES)
    .map(([key, ind]) => scoreIndustry(key, ind, rules.industries?.[key]?.value ?? 0))
    .sort((a, b) => b.score - a.score)
}

const ICON = { prioritaire: "🎯", ok: "✅", éviter: "⚠️ " } as const

/** The ranking, as readable markdown (a standalone artefact regenerated by `npm run radar`). */
export function renderMd(ranked: Scored[]): string {
  const L: string[] = []
  L.push("# Industry radar — which verticals to go after", "")
  L.push("> **Generated by `npm run radar`** (don't edit by hand). Score = ticket × web-decisive ×")
  L.push("> sellable pool (TAM × (1 − franchises)) × recurring. Single source: `industries.ts`.", "")
  L.push(`> ${ranked.length} trades · ${ranked.filter((r) => r.tier === "prioritaire").length} priority.`, "")
  L.push("> ⚠ Some baselines (ticket/tam/franchise) are **estimated, not verified** (the notes `unverified")
  L.push("> research` / `estimated baseline` in `industries.ts`) → read the scores as an ORDER OF PRIORITY, not hard figures.", "")
  L.push("| # | score | tier | trade | their sale's ticket | sellable pool | franchise | status |")
  L.push("|--:|:--:|:--|---|---|--:|--:|:--|")
  ranked.forEach((r, i) => {
    const icon = r.tier === "prioritaire" ? "🎯" : r.tier === "ok" ? "✅" : "⚠️"
    L.push(`| ${i + 1} | **${r.score}** | ${icon} ${TIER_EN[r.tier]} | ${r.label} | ${r.ticket} | ${r.sellableTam.toLocaleString("fr")} | ${r.franchised}% | ${r.scrapable ? "scrapable" : "to wire"} |`)
  })
  L.push("", "🎯 priority ≥73 · ✅ ok 55–72 · ⚠️ avoid <55", "")
  const toWire = ranked.filter((r) => !r.scrapable && r.tier !== "éviter")
  if (toWire.length) {
    L.push("## To wire (premium, not scrapable yet)", "")
    L.push("See the `radar-industries` skill (create an industry): research `osm/naf/terms/chains` →", "an `industries.ts` entry + a `design/industries/<key>.md` profile.", "")
    for (const r of toWire) L.push(`- **${r.label}** (${r.score}) — ${r.ticket}`)
  } else {
    L.push("✅ **Every profitable vertical is wired** (scrapable).")
  }
  return L.join("\n") + "\n"
}

/** One radar line for a trade (baselines, no learning) — the nudge shown when a scrape starts. */
export function radarOneLine(key: string): string | null {
  const ind = INDUSTRIES[key]
  if (!ind) return null
  const r = scoreIndustry(key, ind)
  return `${ICON[r.tier]} radar ${r.score}/100 (${TIER_EN[r.tier]}) — ${r.why}`
}

// --- CLI ---
if (import.meta.url === `file://${process.argv[1]}`) {
  const ranked = await rankIndustries()
  const one = process.argv[2]

  if (one) {
    const r = ranked.find((x) => x.key === one || x.label.includes(one))
    if (!r) { console.error(`Unknown trade: ${one}. Known: ${ranked.map((x) => x.key).join(", ")}`); process.exit(1) }
    console.log(`\n${ICON[r.tier]} ${r.label} — ${r.score}/100 (${TIER_EN[r.tier]})`)
    console.log(`   their sale's ticket: ${r.ticket}`)
    console.log(`   ${r.why}`)
    console.log(`   ${r.scrapable ? "✅ scrapable: npm run scrape -- " + r.key : "⛔ to wire in industries.ts (osm/naf missing)"}`)
  } else {
    console.log(`\n📡 INDUSTRY RADAR — ${ranked.length} verticals (score = ticket × web-decisive × sellable pool × recurring)\n`)
    console.log("  #  score  trade                                         ticket             pool        status")
    console.log("  ─────────────────────────────────────────────────────────────────────────────────────────────")
    ranked.forEach((r, i) => {
      const rank = String(i + 1).padStart(2)
      const sc = `${ICON[r.tier]}${String(r.score).padStart(2)}`
      const lbl = r.label.slice(0, 44).padEnd(44)
      const tk = r.ticket.slice(0, 18).padEnd(18)
      const tam = `${(r.sellableTam / 1000).toFixed(1)}k`.padStart(6)
      console.log(`  ${rank}  ${sc}  ${lbl} ${tk} ${tam}    ${r.scrapable ? "scrapable" : "to wire"}`)
    })
    await mkdir(dirname(MD_PATH), { recursive: true })
    await writeFile(MD_PATH, renderMd(ranked))
    console.log(`\n  📄 ranking written → design/industries/RADAR.md`)
    const toWire = ranked.filter((r) => !r.scrapable && r.tier === "prioritaire")
    console.log("\n  🎯 priority ≥73 · ✅ ok 55–72 · ⚠️ avoid <55")
    if (toWire.length) console.log(`  ➜ TO WIRE: ${toWire.map((r) => `${r.label} (${r.score})`).join(", ")}`)
    console.log("")
  }
}
