-- db/schema.sql · THE schema of the Last Web Studios shared database (Postgres 14+, Supabase included).
--
-- REBUILT on 2026-10-24 from the code's queries (test/helpers/sql-extract.ts lists them all;
-- `npm run test:pg` PREPARES them one by one on a database set up with this file). It was NEVER read from
-- the production database: before applying it to production, compare it with the real database.
--
-- Idempotent and NON-destructive: `CREATE TABLE IF NOT EXISTS`, then `ADD COLUMN IF NOT EXISTS` for each
-- column added over time (an older database converges, no data is touched).
-- Apply: `npm run db:init` (reads DATABASE_URL; TLS through DB_SSL, see packages/shared/pg-options.mjs).
--
-- Conventions: timestamps in epoch MILLISECONDS (BIGINT, read back as Number by db.ts); flags as
-- INTEGER 0/1; the *_json columns are TEXT (JSON serialised by the code), except `data` as JSONB.
-- SOURCE OF TRUTH: the disk (data/prospects, output/sites) stays the source; these tables are a rebuildable
-- INDEX (reindexAll) + the only home of "fresh" state (statuses, ratings, CRM, the batch queue).

-- ════════ the disk's index ════════

-- an indexed prospect sheet (data/prospects/<id>.json); sheet_json = the whole sheet
CREATE TABLE IF NOT EXISTS prospects (
  id                 TEXT PRIMARY KEY,
  industry           TEXT,
  name               TEXT,
  city               TEXT,
  zone               TEXT,
  phone              TEXT,
  email              TEXT,
  existing_url       TEXT,
  screenshot_path    TEXT,
  tagline            TEXT,
  about              TEXT,
  services_json      TEXT,
  brands_json        TEXT,
  opp_score          INTEGER,
  opp_tier           TEXT,
  opp_reasons_json   TEXT,
  sheet_mtime        BIGINT,
  sheet_json         TEXT,
  present            INTEGER NOT NULL DEFAULT 1,
  indexed_at         BIGINT
);
-- registry qualification (npm run qualify: the Recherche d'entreprises API)
ALTER TABLE prospects ADD COLUMN IF NOT EXISTS company_active     BOOLEAN;
ALTER TABLE prospects ADD COLUMN IF NOT EXISTS company_siren      TEXT;
ALTER TABLE prospects ADD COLUMN IF NOT EXISTS company_ca         BIGINT;
ALTER TABLE prospects ADD COLUMN IF NOT EXISTS company_employees  INTEGER;
ALTER TABLE prospects ADD COLUMN IF NOT EXISTS company_checked_at BIGINT;

-- a generation = an output/sites/<prospect>/<dir_slug> folder (e.g. 2026-06-08-composer)
CREATE TABLE IF NOT EXISTS generations (
  prospect_id        TEXT NOT NULL,
  dir_slug           TEXT NOT NULL,
  gen_date           TEXT,
  variant            TEXT,
  has_index          INTEGER NOT NULL DEFAULT 0,
  template           TEXT,
  counts             TEXT,
  generated_label    TEXT,
  has_comment        INTEGER NOT NULL DEFAULT 0,
  control_mtime      BIGINT,
  present            INTEGER NOT NULL DEFAULT 1,
  indexed_at         BIGINT,
  created_at         BIGINT,
  PRIMARY KEY (prospect_id, dir_slug)
);
-- DB-owned state (never overwritten by the reindex): workflow draft → approved → drafted → sent (+ rejected…)
ALTER TABLE generations ADD COLUMN IF NOT EXISTS status            TEXT DEFAULT 'draft';
ALTER TABLE generations ADD COLUMN IF NOT EXISTS status_changed_at BIGINT;
ALTER TABLE generations ADD COLUMN IF NOT EXISTS sent_at           BIGINT;
ALTER TABLE generations ADD COLUMN IF NOT EXISTS love              INTEGER DEFAULT 0;   -- ♥ 0-3
ALTER TABLE generations ADD COLUMN IF NOT EXISTS scores_json       TEXT;                -- 0-100 rating per axis
CREATE INDEX IF NOT EXISTS generations_present_idx ON generations (present, gen_date DESC);
CREATE INDEX IF NOT EXISTS generations_status_idx  ON generations (status) WHERE present = 1;

-- a prospect's media file (data/assets/<id>/…); `included` = DB-owned (left out of the library if 0)
CREATE TABLE IF NOT EXISTS assets (
  prospect_id        TEXT NOT NULL,
  rel_path           TEXT NOT NULL,
  kind               TEXT,
  mime               TEXT,
  mtime              BIGINT,
  hash               TEXT,
  present            INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (prospect_id, rel_path)
);
ALTER TABLE assets ADD COLUMN IF NOT EXISTS included INTEGER DEFAULT 1;

-- log of the asset swaps made from the cockpit (append-only)
CREATE TABLE IF NOT EXISTS asset_events (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prospect_id        TEXT NOT NULL,
  action             TEXT NOT NULL,
  old_rel_path       TEXT,
  new_rel_path       TEXT,
  reason             TEXT,
  actor              TEXT,
  created_at         BIGINT
);

-- the cockpit's "brain": skills from .claude/skills and ideas from docs/skillstash.md
CREATE TABLE IF NOT EXISTS skills (
  name               TEXT PRIMARY KEY,
  status             TEXT,
  kind               TEXT,
  description        TEXT,
  has_feedback       INTEGER NOT NULL DEFAULT 0,
  file_mtime         BIGINT,
  present            INTEGER NOT NULL DEFAULT 1,
  indexed_at         BIGINT
);
CREATE TABLE IF NOT EXISTS ideas (
  slug               TEXT PRIMARY KEY,
  idea               TEXT,
  signal             TEXT,
  note               TEXT,
  category           TEXT,
  drafted            INTEGER NOT NULL DEFAULT 0,
  present            INTEGER NOT NULL DEFAULT 1,
  indexed_at         BIGINT
);

-- small system values (e.g. last_full_reindex_at, schema_applied_at)
CREATE TABLE IF NOT EXISTS meta (
  key                TEXT PRIMARY KEY,
  value              TEXT,
  updated_at         BIGINT
);

-- ════════ fresh state (DB-owned) ════════

-- THE batch QUEUE: the cockpit pushes, the worker (box) pulls (claim FOR UPDATE SKIP LOCKED)
CREATE TABLE IF NOT EXISTS batch_requests (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status             TEXT NOT NULL DEFAULT 'queued',   -- queued | running | done | error | canceled
  mode               TEXT NOT NULL DEFAULT 'composer', -- composer | template-fill | edit | research
  industry           TEXT,
  seed               TEXT,
  lim                INTEGER,
  force_flag         INTEGER NOT NULL DEFAULT 0,
  requested_by       TEXT,
  note               TEXT,
  worker             TEXT,
  log                TEXT,
  result_json        TEXT,
  created_at         BIGINT NOT NULL,
  started_at         BIGINT,
  finished_at        BIGINT,
  retry_after        BIGINT,
  attempts           INTEGER NOT NULL DEFAULT 0,
  params_json        TEXT
);
CREATE INDEX IF NOT EXISTS batch_requests_queue_idx ON batch_requests (status, retry_after, created_at);

-- the call CRM (2 pipelines: hot = call0→relance1→relance2→relance3→nurturing · closing = demo→propal→nego→signature; the stage names are stored values)
CREATE TABLE IF NOT EXISTS crm_leads (
  prospect_id        TEXT PRIMARY KEY,
  pipeline           TEXT NOT NULL DEFAULT 'hot',
  stage              TEXT NOT NULL DEFAULT 'call0',
  call_count         INTEGER NOT NULL DEFAULT 0,
  rdv_at             BIGINT,
  nurturing_until    BIGINT,
  notes_json         TEXT NOT NULL DEFAULT '[]',   -- [{at, outcome:'reach'|'unreach'|'rdv'|'note'|'mail', text, slot?}]
  linkedin           TEXT,                          -- 'added' | 'messaged'
  call_script        TEXT,
  research_json      TEXT,
  updated_at         BIGINT
);
ALTER TABLE crm_leads ADD COLUMN IF NOT EXISTS call_script   TEXT;
ALTER TABLE crm_leads ADD COLUMN IF NOT EXISTS research_json TEXT;
ALTER TABLE crm_leads ADD COLUMN IF NOT EXISTS assigned_to   TEXT;      -- the operator who calls (NULL = unassigned)
ALTER TABLE crm_leads ADD COLUMN IF NOT EXISTS answered      INTEGER;   -- 1 answered · 0 no answer · NULL never called

-- the cold-email sequencer's state (one row per prospect, the whole sequence as JSON)
CREATE TABLE IF NOT EXISTS sequencer_state (
  prospect_id        TEXT PRIMARY KEY,
  data               JSONB NOT NULL,
  updated_at         BIGINT
);

-- the invoices issued (JSON store, number = legal key)
CREATE TABLE IF NOT EXISTS invoices (
  number             TEXT PRIMARY KEY,
  data               JSONB NOT NULL,
  created_at         BIGINT
);

-- the outreach log: what the prospect does after the email and what the mailbox sends back (append-only).
-- Written by the cockpit's public /t/ endpoint (click, RFC 8058 unsubscribe), the sequencer's reply
-- reader (reply, "STOP", bounce), the CLI (complaint) and the CRM (a call's outcome = the learning's mirror).
-- Read by the sequencer (click-gated escalation, stop, Hot Lead), the circuit breaker and the Machine view.
-- Replaces the table of the old Supabase edge function (never versioned). See outreach/tracking/README.md.
CREATE TABLE IF NOT EXISTS outreach_events (
  id                 TEXT PRIMARY KEY,                 -- uuid, or a stable id (ev-<hash>) for idempotent replays
  tracking_id        TEXT NOT NULL DEFAULT '',         -- the send (sends.jsonl); '' = tied to the prospect only
  prospect_id        TEXT,
  type               TEXT NOT NULL,                    -- click | unsub | reply | bounce | complaint | outcome
  at                 BIGINT NOT NULL,                  -- epoch ms
  url                TEXT,                             -- a click's destination (signed in the link)
  ua                 TEXT,                             -- the click's user-agent (shortened)
  suspect            INTEGER NOT NULL DEFAULT 0,       -- 1 = a likely link scanner (ignored by the escalation)
  source             TEXT,                             -- track | reader | cli | crm
  data_json          TEXT
);
CREATE INDEX IF NOT EXISTS outreach_events_tracking_idx ON outreach_events (tracking_id, type);
CREATE INDEX IF NOT EXISTS outreach_events_at_idx       ON outreach_events (at);
CREATE INDEX IF NOT EXISTS outreach_events_prospect_idx ON outreach_events (prospect_id, type);
