-- db/schema.sql · LE schéma de la base partagée Last Web Studios (Postgres 14+, Supabase compris).
--
-- RECONSTRUIT le 2026-10-24 à partir des requêtes du code (test/helpers/sql-extract.ts les liste toutes ;
-- `npm run test:pg` les PRÉPARE une à une sur une base montée avec ce fichier). Il n'a JAMAIS été lu depuis
-- la base de production : avant de l'appliquer sur la prod, le confronter à Supabase (Yann / naly).
--
-- Idempotent et NON destructif : `CREATE TABLE IF NOT EXISTS` puis `ADD COLUMN IF NOT EXISTS` pour chaque
-- colonne ajoutée au fil du temps (une base plus ancienne converge, aucune donnée n'est touchée).
-- Appliquer : `npm run db:init` (lit DATABASE_URL ; TLS via DB_SSL, cf. packages/shared/pg-options.mjs).
--
-- Conventions : horodatages en epoch MILLISECONDES (BIGINT, relus en Number par db.ts) ; drapeaux en
-- INTEGER 0/1 ; les colonnes *_json sont du TEXT (JSON sérialisé par le code), sauf `data` en JSONB.
-- MODÈLE DE VÉRITÉ : le disque (data/prospects, output/sites) reste la source ; ces tables sont un INDEX
-- reconstructible (reindexAll) + la seule maison de l'état « neuf » (statuts, notes, CRM, file de batchs).

-- ════════ index du disque ════════

-- une fiche prospect (data/prospects/<id>.json) indexée ; sheet_json = la fiche entière
CREATE TABLE IF NOT EXISTS prospects (
  id                 TEXT PRIMARY KEY,
  industry           TEXT,
  name               TEXT,
  city               TEXT,
  zone               TEXT,
  phone              TEXT,
  email              TEXT,
  existing_url       TEXT,
  screenshot_path    TEXT,
  tagline            TEXT,
  about              TEXT,
  services_json      TEXT,
  brands_json        TEXT,
  opp_score          INTEGER,
  opp_tier           TEXT,
  opp_reasons_json   TEXT,
  sheet_mtime        BIGINT,
  sheet_json         TEXT,
  present            INTEGER NOT NULL DEFAULT 1,
  indexed_at         BIGINT
);
-- qualification registre (npm run qualify : API Recherche d'entreprises)
ALTER TABLE prospects ADD COLUMN IF NOT EXISTS company_active     BOOLEAN;
ALTER TABLE prospects ADD COLUMN IF NOT EXISTS company_siren      TEXT;
ALTER TABLE prospects ADD COLUMN IF NOT EXISTS company_ca         BIGINT;
ALTER TABLE prospects ADD COLUMN IF NOT EXISTS company_employees  INTEGER;
ALTER TABLE prospects ADD COLUMN IF NOT EXISTS company_checked_at BIGINT;

-- une génération = un dossier output/sites/<prospect>/<dir_slug> (ex. 2026-06-08-composer)
CREATE TABLE IF NOT EXISTS generations (
  prospect_id        TEXT NOT NULL,
  dir_slug           TEXT NOT NULL,
  gen_date           TEXT,
  variant            TEXT,
  has_index          INTEGER NOT NULL DEFAULT 0,
  template           TEXT,
  counts             TEXT,
  generated_label    TEXT,
  has_comment        INTEGER NOT NULL DEFAULT 0,
  control_mtime      BIGINT,
  present            INTEGER NOT NULL DEFAULT 1,
  indexed_at         BIGINT,
  created_at         BIGINT,
  PRIMARY KEY (prospect_id, dir_slug)
);
-- état DB-owned (jamais écrasé par le reindex) : workflow draft → approved → drafted → sent (+ rejected…)
ALTER TABLE generations ADD COLUMN IF NOT EXISTS status            TEXT DEFAULT 'draft';
ALTER TABLE generations ADD COLUMN IF NOT EXISTS status_changed_at BIGINT;
ALTER TABLE generations ADD COLUMN IF NOT EXISTS sent_at           BIGINT;
ALTER TABLE generations ADD COLUMN IF NOT EXISTS love              INTEGER DEFAULT 0;   -- ♥ 0-3
ALTER TABLE generations ADD COLUMN IF NOT EXISTS scores_json       TEXT;                -- notation 0-100 par axe
CREATE INDEX IF NOT EXISTS generations_present_idx ON generations (present, gen_date DESC);
CREATE INDEX IF NOT EXISTS generations_status_idx  ON generations (status) WHERE present = 1;

-- un média d'un prospect (data/assets/<id>/…) ; `included` = DB-owned (exclu de la bibliothèque si 0)
CREATE TABLE IF NOT EXISTS assets (
  prospect_id        TEXT NOT NULL,
  rel_path           TEXT NOT NULL,
  kind               TEXT,
  mime               TEXT,
  mtime              BIGINT,
  hash               TEXT,
  present            INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (prospect_id, rel_path)
);
ALTER TABLE assets ADD COLUMN IF NOT EXISTS included INTEGER DEFAULT 1;

-- journal des échanges d'assets faits depuis le cockpit (append-only)
CREATE TABLE IF NOT EXISTS asset_events (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prospect_id        TEXT NOT NULL,
  action             TEXT NOT NULL,
  old_rel_path       TEXT,
  new_rel_path       TEXT,
  reason             TEXT,
  actor              TEXT,
  created_at         BIGINT
);

-- le « brain » du cockpit : skills de .claude/skills et idées de docs/skillstash.md
CREATE TABLE IF NOT EXISTS skills (
  name               TEXT PRIMARY KEY,
  status             TEXT,
  kind               TEXT,
  description        TEXT,
  has_feedback       INTEGER NOT NULL DEFAULT 0,
  file_mtime         BIGINT,
  present            INTEGER NOT NULL DEFAULT 1,
  indexed_at         BIGINT
);
CREATE TABLE IF NOT EXISTS ideas (
  slug               TEXT PRIMARY KEY,
  idea               TEXT,
  signal             TEXT,
  note               TEXT,
  category           TEXT,
  drafted            INTEGER NOT NULL DEFAULT 0,
  present            INTEGER NOT NULL DEFAULT 1,
  indexed_at         BIGINT
);

-- petites valeurs système (ex. last_full_reindex_at, schema_applied_at)
CREATE TABLE IF NOT EXISTS meta (
  key                TEXT PRIMARY KEY,
  value              TEXT,
  updated_at         BIGINT
);

-- ════════ état neuf (DB-owned) ════════

-- LA FILE des batchs : le cockpit empile, le worker (box) dépile (claim FOR UPDATE SKIP LOCKED)
CREATE TABLE IF NOT EXISTS batch_requests (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status             TEXT NOT NULL DEFAULT 'queued',   -- queued | running | done | error | canceled
  mode               TEXT NOT NULL DEFAULT 'composer', -- composer | template-fill | edit | research
  industry           TEXT,
  seed               TEXT,
  lim                INTEGER,
  force_flag         INTEGER NOT NULL DEFAULT 0,
  requested_by       TEXT,
  note               TEXT,
  worker             TEXT,
  log                TEXT,
  result_json        TEXT,
  created_at         BIGINT NOT NULL,
  started_at         BIGINT,
  finished_at        BIGINT,
  retry_after        BIGINT,
  attempts           INTEGER NOT NULL DEFAULT 0,
  params_json        TEXT
);
CREATE INDEX IF NOT EXISTS batch_requests_queue_idx ON batch_requests (status, retry_after, created_at);

-- le CRM d'appel (2 pipelines : hot = call0→relance1→relance2→relance3→nurturing · closing = demo→propal→nego→signature)
CREATE TABLE IF NOT EXISTS crm_leads (
  prospect_id        TEXT PRIMARY KEY,
  pipeline           TEXT NOT NULL DEFAULT 'hot',
  stage              TEXT NOT NULL DEFAULT 'call0',
  call_count         INTEGER NOT NULL DEFAULT 0,
  rdv_at             BIGINT,
  nurturing_until    BIGINT,
  notes_json         TEXT NOT NULL DEFAULT '[]',   -- [{at, outcome:'reach'|'unreach'|'rdv'|'note'|'mail', text, slot?}]
  linkedin           TEXT,                          -- 'added' | 'messaged'
  call_script        TEXT,
  research_json      TEXT,
  updated_at         BIGINT
);
ALTER TABLE crm_leads ADD COLUMN IF NOT EXISTS call_script   TEXT;
ALTER TABLE crm_leads ADD COLUMN IF NOT EXISTS research_json TEXT;
ALTER TABLE crm_leads ADD COLUMN IF NOT EXISTS assigned_to   TEXT;      -- opérateur qui appelle (NULL = non attribué)
ALTER TABLE crm_leads ADD COLUMN IF NOT EXISTS answered      INTEGER;   -- 1 a répondu · 0 pas de réponse · NULL jamais appelé

-- l'état du séquenceur cold-email (une ligne par prospect, la séquence entière en JSON)
CREATE TABLE IF NOT EXISTS sequencer_state (
  prospect_id        TEXT PRIMARY KEY,
  data               JSONB NOT NULL,
  updated_at         BIGINT
);

-- les factures émises (store JSON, numéro = clé légale)
CREATE TABLE IF NOT EXISTS invoices (
  number             TEXT PRIMARY KEY,
  data               JSONB NOT NULL,
  created_at         BIGINT
);

-- le journal outreach : ce que le prospect fait après le mail et ce que la boîte renvoie (append-only).
-- Écrit par l'endpoint public /t/ du cockpit (clic, désinscription RFC 8058), le lecteur de réponses du
-- séquenceur (réponse, « STOP », bounce), la CLI (plainte) et le CRM (issue d'un appel = miroir du learning).
-- Lu par le séquenceur (escalade gatée au clic, arrêt, Hot Lead), le disjoncteur et la vue Machine.
-- Remplace la table de l'ancienne edge function Supabase (jamais versionnée). Cf. outreach/tracking/README.md.
CREATE TABLE IF NOT EXISTS outreach_events (
  id                 TEXT PRIMARY KEY,                 -- uuid, ou id stable (ev-<hash>) pour les rejeux idempotents
  tracking_id        TEXT NOT NULL DEFAULT '',         -- l'envoi (sends.jsonl) ; '' = rattaché au seul prospect
  prospect_id        TEXT,
  type               TEXT NOT NULL,                    -- click | unsub | reply | bounce | complaint | outcome
  at                 BIGINT NOT NULL,                  -- epoch ms
  url                TEXT,                             -- destination d'un clic (signée dans le lien)
  ua                 TEXT,                             -- user-agent du clic (tronqué)
  suspect            INTEGER NOT NULL DEFAULT 0,       -- 1 = scanner de liens probable (ignoré par l'escalade)
  source             TEXT,                             -- track | reader | cli | crm
  data_json          TEXT
);
CREATE INDEX IF NOT EXISTS outreach_events_tracking_idx ON outreach_events (tracking_id, type);
CREATE INDEX IF NOT EXISTS outreach_events_at_idx       ON outreach_events (at);
CREATE INDEX IF NOT EXISTS outreach_events_prospect_idx ON outreach_events (prospect_id, type);
