/**
 * G5: a fresh install sets up its database. `npm run db:init` twice in a row without an error, then EVERY
 * SQL query in the code is PREPARED on that database (tables and columns validated, nothing run).
 */
import { test, before, after } from "node:test"
import assert from "node:assert/strict"
import { freshDatabase } from "../helpers/pg.ts"
import { npmRun } from "../helpers/proc.ts"
import { extractSql, toPg } from "../helpers/sql-extract.ts"
import { TABLES } from "../../db/init.ts"

let db: Awaited<ReturnType<typeof freshDatabase>>
before(async () => { db = await freshDatabase() })
after(async () => { await db?.drop() })

test("npm run db:init: applied twice in a row, idempotent, 12/12 tables", async () => {
  for (let i = 0; i < 2; i++) {
    const r = await npmRun(process.cwd(), "db:init", [], { env: { DATABASE_URL: db.url, DB_SSL: "disable" } })
    assert.equal(r.code, 0, r.out)
    assert.match(r.stdout, new RegExp(`✓ Database ready .* ${TABLES.length}/${TABLES.length} tables`))
    assert.doesNotMatch(r.out, /NOTICE/, "the \"already exists, skipping\" NOTICEs are silenced")
  }
  const rows = await db.sql`SELECT value FROM meta WHERE key = 'schema_applied_at'`
  assert.equal(rows.length, 1)
})

test("DB_SSL unset + host 127.0.0.1: no TLS by default, the connection works", async () => {
  const r = await npmRun(process.cwd(), "db:init", [], { env: { DATABASE_URL: db.url, DB_SSL: "" } })
  assert.equal(r.code, 0, r.out)
})

test("DB_SSL=require on a Postgres without TLS: a clear failure, with the DB_SSL=disable hint", async () => {
  const r = await npmRun(process.cwd(), "db:init", [], { env: { DATABASE_URL: db.url, DB_SSL: "require" } })
  assert.notEqual(r.code, 0)
  assert.match(r.stderr, /DB_SSL=disable|TLS|SSL/)
})

test("every SQL query in the code PREPARES on the schema (tables + columns)", async () => {
  const stmts = extractSql(".")
  const failures: string[] = []
  let n = 0
  for (const s of stmts) {
    const q = s.kind === "tagged" ? s.sql : toPg(s.sql)
    if (/^\s*(CREATE|ALTER)\b/i.test(q)) {
      try { await db.sql.unsafe(q) } catch (e) { failures.push(`${s.file}:${s.line} ${(e as Error).message}`) }
      continue
    }
    const name = `p${n++}`
    try { await db.sql.unsafe(`PREPARE ${name} AS ${q}`); await db.sql.unsafe(`DEALLOCATE ${name}`) }
    catch (e) { failures.push(`${s.file}:${s.line} ${(e as Error).message} :: ${q.replace(/\s+/g, " ").slice(0, 140)}`) }
  }
  assert.ok(n >= 70, `only ${n} queries prepared`)
  assert.deepEqual(failures, [])
})

test("an OLDER database (each table cut down to its key, with rows): db:init adds ALL the missing columns, losing nothing", async () => {
  // blitz test of 24/10: `CREATE TABLE IF NOT EXISTS` does not touch a table that already exists; only 16 columns
  // had their `ADD COLUMN IF NOT EXISTS`. A database set up by hand or by an earlier version kept gaps.
  const old = await freshDatabase()
  try {
    await old.sql.unsafe(`
      CREATE TABLE prospects (id TEXT PRIMARY KEY);
      CREATE TABLE generations (prospect_id TEXT NOT NULL, dir_slug TEXT NOT NULL, PRIMARY KEY (prospect_id, dir_slug));
      CREATE TABLE assets (prospect_id TEXT NOT NULL, rel_path TEXT NOT NULL, PRIMARY KEY (prospect_id, rel_path));
      CREATE TABLE asset_events (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
      CREATE TABLE skills (name TEXT PRIMARY KEY);
      CREATE TABLE ideas (slug TEXT PRIMARY KEY);
      CREATE TABLE meta (key TEXT PRIMARY KEY, value TEXT);
      CREATE TABLE batch_requests (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, status TEXT);
      CREATE TABLE crm_leads (prospect_id TEXT PRIMARY KEY);
      CREATE TABLE sequencer_state (prospect_id TEXT PRIMARY KEY);
      CREATE TABLE invoices (number TEXT PRIMARY KEY);
      INSERT INTO prospects (id) VALUES ('orvane-piscines-valmont-sur-lys');
      INSERT INTO batch_requests (status) VALUES ('done');
      INSERT INTO invoices (number) VALUES ('2026-001');
      INSERT INTO meta (key, value) VALUES ('ancienne', 'valeur');`)
    const r = await npmRun(process.cwd(), "db:init", [], { env: { DATABASE_URL: old.url, DB_SSL: "disable" } })
    assert.equal(r.code, 0, r.out)
    assert.match(r.stdout, /column\(s\) added to an older database/)
    const failures: string[] = []
    let n = 0
    for (const s of extractSql(".")) {
      const q = s.kind === "tagged" ? s.sql : toPg(s.sql)
      if (/^\s*(CREATE|ALTER)\b/i.test(q)) continue
      const name = `u${n++}`
      try { await old.sql.unsafe(`PREPARE ${name} AS ${q}`); await old.sql.unsafe(`DEALLOCATE ${name}`) }
      catch (e) { failures.push(`${s.file}:${s.line} ${(e as Error).message}`) }
    }
    assert.deepEqual(failures, [], "every query in the code passes on the upgraded database")
    assert.equal((await old.sql`SELECT count(*)::int AS n FROM prospects`)[0].n, 1, "the existing rows are kept")
    assert.equal((await old.sql`SELECT value FROM meta WHERE key = 'ancienne'`)[0].value, "valeur")
    const again = await npmRun(process.cwd(), "db:init", [], { env: { DATABASE_URL: old.url, DB_SSL: "disable" } })
    assert.equal(again.code, 0, again.out)
    assert.doesNotMatch(again.stdout, /column\(s\) added/, "the 2nd time, nothing left to add")
  } finally { await old.drop() }
})
