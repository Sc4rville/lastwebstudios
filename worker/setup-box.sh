#!/usr/bin/env bash
# setup-box.sh — installs THE WORKER on the box (Hetzner). Run it OVER SSH on the server, once.
#
# Idempotent: safe to run again. Does: Node + Claude Code + the repo + Playwright + the systemd
# service. The ONLY interactive step left on YOUR side: `claude setup-token` (the PLAN's token)
# and pasting DATABASE_URL — the script guides you.
#
#   ssh root@<box-IP>
#   # (get the repo once to have this script, or copy it over)
#   git clone https://github.com/<toi>/lastwebstudios.git ~/lws && cd ~/lws
#   bash worker/setup-box.sh
#
set -euo pipefail

LWS_DIR="${LWS_DIR:-$HOME/lws}"
REPO="${LWS_REPO:-https://github.com/<toi>/lastwebstudios.git}"
NODE_MAJOR="${NODE_MAJOR:-24}"

say() { printf '\n\033[1;36m▶ %s\033[0m\n' "$*"; }
ok()  { printf '\033[1;32m✓ %s\033[0m\n' "$*"; }
warn(){ printf '\033[1;33m⚠ %s\033[0m\n' "$*"; }

# ── 1. Node ───────────────────────────────────────────────────────────────────
if ! command -v node >/dev/null 2>&1 || [ "$(node -p 'process.versions.node.split(".")[0]')" -lt "$NODE_MAJOR" ]; then
  say "Installing Node $NODE_MAJOR (NodeSource)…"
  curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | bash -
  apt-get install -y nodejs
fi
ok "Node $(node -v) · npm $(npm -v)"

# ── 2. Claude Code (the CLI) ────────────────────────────────────────────────────
if ! command -v claude >/dev/null 2>&1; then
  say "Installing Claude Code…"
  npm install -g @anthropic-ai/claude-code
fi
ok "Claude Code : $(claude --version 2>/dev/null || echo 'installed')"

# ── 3. The repo ─────────────────────────────────────────────────────────────────
if [ ! -d "$LWS_DIR/.git" ]; then
  say "Cloning the repo into $LWS_DIR…"
  git clone "$REPO" "$LWS_DIR"
else
  say "Updating the repo ($LWS_DIR)…"
  git -C "$LWS_DIR" pull --ff-only || warn "git pull is not a fast-forward — fix it by hand"
fi
cd "$LWS_DIR"

say "npm install…"
npm install

# ── 4. Playwright + browsers (the scraping / avant.png) ─────────────────────────
say "Playwright + Chromium (+ system deps)…"
npx playwright install --with-deps chromium

# ── 5. .env (DATABASE_URL + plan token + API key) ───────────────────────────────
if [ ! -f "$LWS_DIR/.env" ]; then
  say "Creating $LWS_DIR/.env"
  cat > "$LWS_DIR/.env" <<'EOF'
# The Supabase pooler (IPv4) — Supabase → Settings → Database → Connection pooling (session mode)
DATABASE_URL=postgresql://postgres.<ref>:PASSWORD@aws-0-eu-west-1.pooler.supabase.com:5432/postgres
# The PLAN's token (generated by `claude setup-token`) — runs the composer on the subscription, not the API
CLAUDE_CODE_OAUTH_TOKEN=
# The API key — for the cheap extraction (structuring) the composer runs again; negligible
ANTHROPIC_API_KEY=
EOF
  warn "Edit $LWS_DIR/.env: paste the real DATABASE_URL, the API key, AND the plan token (step 6)."
else
  ok ".env already there (not overwritten)"
fi

# ── 6. The PLAN's token (interactive — YOUR step) ───────────────────────────────
if ! grep -q '^CLAUDE_CODE_OAUTH_TOKEN=.\+' "$LWS_DIR/.env" 2>/dev/null; then
  warn "Plan token missing. Run:   claude setup-token"
  warn "then paste the value into $LWS_DIR/.env  →  CLAUDE_CODE_OAUTH_TOKEN=..."
  warn "(that is what runs the generation ON THE PLAN and not on the pay-per-token API)"
fi

# ── 7. systemd user service ─────────────────────────────────────────────────────
say "Installing the systemd service (lws-worker)…"
mkdir -p "$HOME/.config/systemd/user"
# WorkingDirectory set to the repo's real path
sed "s|WorkingDirectory=%h/lws|WorkingDirectory=$LWS_DIR|; s|%h/lws/.env|$LWS_DIR/.env|" \
  "$LWS_DIR/worker/lws-worker.service" > "$HOME/.config/systemd/user/lws-worker.service"
loginctl enable-linger "$USER" 2>/dev/null || warn "enable-linger failed (the service will not survive logging out) — run again as root if needed"
systemctl --user daemon-reload

ok "Installed. Once the .env is complete (DATABASE_URL + CLAUDE_CODE_OAUTH_TOKEN):"
cat <<EOF

  systemctl --user enable --now lws-worker     # starts it + at boot
  systemctl --user status lws-worker           # check that it runs
  journalctl --user -u lws-worker -f           # follow the logs live

Quick test: from the cockpit, click "start a batch" → the worker should take it here.
EOF
